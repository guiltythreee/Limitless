def cue_references_label(question):
    fields=[]
    for k in ("text","assertion","reason","keyExplanation","concise","detailed","why","concept"):
        v=question.get(k)
        if isinstance(v,str): fields.append(v)
    opts=question.get("options")
    if isinstance(opts,list):
        fields.extend(str(x.get("text", "")) for x in opts if isinstance(x,dict))
    s=" ".join(fields)
    pats=[r'\b(?:option|choice)\s*\(?\s*[a-d]\s*\)?\b',
          r'\b(?:the )?(?:correct )?(?:answer|choice|option)\s*(?:is|=|:)?\s*(?:option\s*)?\(?\s*[a-d]\s*\)?\b',
          r'\b(?:first|second|third|fourth)\s+option\b']
    return any(re.search(p,s,re.I) for p in pats)

