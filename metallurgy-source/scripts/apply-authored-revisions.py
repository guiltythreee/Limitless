def ts_skip(src, i):
    """Skip a string/comment token beginning at i; return first index after it."""
    n=len(src); c=src[i]
    if c in ('"', "'", '`'):
        q=c; i+=1
        while i<n:
            if src[i]=='\\': i+=2; continue
            if src[i]==q: return i+1
            i+=1
        raise SafeStop("Unterminated string/template in TypeScript source")
    if src.startswith('//', i):
        j=src.find('\n',i+2); return n if j<0 else j+1
    if src.startswith('/*', i):
        j=src.find('*/',i+2)
        if j<0: raise SafeStop("Unterminated block comment in TypeScript source")
        return j+2
    return i

def matching_brace(src, start):
    if src[start] != '{': raise SafeStop("Internal parser error: expected opening brace")
    depth=0; i=start
    while i<len(src):
        j=ts_skip(src,i)
        if j!=i:
            i=j; continue
        c=src[i]
        if c=='{': depth+=1
        elif c=='}':
            depth-=1
            if depth==0: return i
        i+=1
    raise SafeStop("Unbalanced TypeScript object literal")

def ts_question_span(src, qid):
    pat=re.compile(r'\bid\s*:\s*["\']'+re.escape(qid)+r'["\']')
    m=pat.search(src)
    if not m: raise SafeStop(f"MT203 source question {qid} not found")
    if pat.search(src, m.end()): raise SafeStop(f"MT203 source question ID {qid} is duplicated")
    start=src.rfind('{',0,m.start())
    if start<0: raise SafeStop(f"Could not locate question object for {qid}")
    # Ensure this is the nearest unclosed object before the id, not a brace in a comment/string.
    stack=[]; i=0
    while i<m.start():
        j=ts_skip(src,i)
        if j!=i:
            i=j; continue
        if src[i]=='{': stack.append(i)
        elif src[i]=='}' and stack: stack.pop()
        i+=1
    if not stack: raise SafeStop(f"Could not locate enclosing question object for {qid}")
    start=stack[-1]
    end=matching_brace(src,start)
    if end<m.end(): raise SafeStop(f"Malformed question object for {qid}")
    return start,end+1

def ts_top_properties(obj):
    """Return property value spans for a plain TS object literal."""
    if not (obj.startswith('{') and obj.endswith('}')): raise SafeStop("Expected TS object literal")
    props={}; i=1; end=len(obj)-1
    while i<end:
        while i<end and (obj[i].isspace() or obj[i]==','): i+=1
        if i>=end: break
        key_start=i
        # plain identifiers or quoted keys
        if obj[i] in ('"', "'"):
            j=ts_skip(obj,i); raw=obj[i:j]
            try: key=json.loads(raw) if raw.startswith('"') else ast.literal_eval(raw)
            except Exception as e: raise SafeStop(f"Unsupported TS property key {raw}: {e}")
            i=j
        else:
            m=re.match(r'[A-Za-z_$][\w$]*',obj[i:])
            if not m: raise SafeStop(f"Could not parse TS property near: {obj[i:i+60]!r}")
            key=m.group(0); i+=len(key)
        while i<end and obj[i].isspace(): i+=1
        if i>=end or obj[i] != ':':
            # Skip non-key constructs rather than guessing; these question objects should be plain key:value pairs.
            raise SafeStop(f"Expected colon after TS property {key!r}")
        i+=1
        while i<end and obj[i].isspace(): i+=1
        vs=i; curly=square=paren=0
        while i<end:
            j=ts_skip(obj,i)
            if j!=i:
                i=j; continue
            c=obj[i]
            if c=='{': curly+=1
            elif c=='}':
                if curly==0 and square==0 and paren==0: break
                curly-=1
            elif c=='[': square+=1
            elif c==']': square-=1
            elif c=='(': paren+=1
            elif c==')': paren-=1
            elif c==',' and curly==0 and square==0 and paren==0: break
            i+=1
        ve=i
        while ve>vs and obj[ve-1].isspace(): ve-=1
        if key in props: raise SafeStop(f"Duplicate TS property {key!r}")
        props[key]=(vs,ve)
        if i<end and obj[i]==',': i+=1
    return props

def parse_ts_literal(src, pos=0):
    """Small parser for JSON-like TS literals used by the question bank."""
    i=pos
    while i<len(src) and src[i].isspace(): i+=1
    if i>=len(src): raise SafeStop("Unexpected end while parsing TS literal")
    c=src[i]
    if c in ('"', "'"):
        j=ts_skip(src,i); raw=src[i:j]
        try: return (json.loads(raw) if c=='"' else ast.literal_eval(raw)), j
        except Exception as e: raise SafeStop(f"Could not parse TS string literal {raw[:50]!r}: {e}")
    if c=='[':
        out=[]; i+=1
        while True:
            while i<len(src) and (src[i].isspace() or src[i]==','): i+=1
            if i>=len(src): raise SafeStop("Unterminated TS array")
            if src[i]==']': return out,i+1
            v,i=parse_ts_literal(src,i); out.append(v)
            while i<len(src) and src[i].isspace(): i+=1
            if i<len(src) and src[i]==',': i+=1
            elif i<len(src) and src[i]==']': return out,i+1
            else: raise SafeStop("Expected comma or ] in TS array")
    if c=='{':
        out={}; i+=1
        while True:
            while i<len(src) and (src[i].isspace() or src[i]==','): i+=1
            if i>=len(src): raise SafeStop("Unterminated TS object")
            if src[i]=='}': return out,i+1
            if src[i] in ('"', "'"):
                j=ts_skip(src,i); raw=src[i:j]
                key=json.loads(raw) if src[i]=='"' else ast.literal_eval(raw); i=j
            else:
                m=re.match(r'[A-Za-z_$][\w$]*',src[i:])
                if not m: raise SafeStop(f"Could not parse TS object key near {src[i:i+40]!r}")
                key=m.group(0); i+=len(key)
            while i<len(src) and src[i].isspace(): i+=1
            if i>=len(src) or src[i] != ':': raise SafeStop(f"Expected colon for TS key {key}")
            v,i=parse_ts_literal(src,i+1); out[key]=v
            while i<len(src) and src[i].isspace(): i+=1
            if i<len(src) and src[i]==',': i+=1
            elif i<len(src) and src[i]=='}': return out,i+1
            else: raise SafeStop("Expected comma or } in TS object")
    for lit,val in (("true",True),("false",False),("null",None),("undefined",None)):
        if src.startswith(lit,i) and (i+len(lit)==len(src) or not (src[i+len(lit)].isalnum() or src[i+len(lit)]=='_')): return val,i+len(lit)
    m=re.match(r'-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?',src[i:])
    if m:
        raw=m.group(0); return (float(raw) if any(x in raw for x in '.eE') else int(raw)),i+len(raw)
    raise SafeStop(f"Unsupported TS literal near: {src[i:i+50]!r}")

def ts_indent_at(src, pos):
    line=src.rfind('\n',0,pos)+1
    return re.match(r'\s*',src[line:pos]).group(0)

def ts_render(value, indent):
    if isinstance(value,str): return json.dumps(value,ensure_ascii=False)
    if value is None: return "null"
    if value is True: return "true"
    if value is False: return "false"
    if isinstance(value,(int,float)): return str(value)
    if isinstance(value,list):
        if not value: return "[]"
        unit="  "; inner=indent+unit
        return "[\n"+",\n".join(inner+ts_render(v,inner) for v in value)+"\n"+indent+"]"
    if isinstance(value,dict):
        if not value: return "{}"
        unit="  "; inner=indent+unit; lines=[]
        for k,v in value.items():
            key=k if re.match(r'^[A-Za-z_$][\w$]*$',str(k)) else json.dumps(str(k),ensure_ascii=False)
            lines.append(inner+key+": "+ts_render(v,inner)+",")
        return "{\n"+"\n".join(lines)+"\n"+indent+"}"
    raise SafeStop(f"Cannot render TS value of type {type(value).__name__}")

def update_ts_object(src, qid, updates):
    start,end=ts_question_span(src,qid); obj=src[start:end]; props=ts_top_properties(obj)
    indent=ts_indent_at(src,start)+"  "
    repl=[]; missing=[]
    for key,val in updates.items():
        if key in props:
            a,b=props[key]; repl.append((a,b,ts_render(val,indent)))
        else: missing.append((key,val))
    for a,b,val in sorted(repl,reverse=True): obj=obj[:a]+val+obj[b:]
    if missing:
        close=obj.rfind('}')
        prefix=obj[:close].rstrip()
        add_comma="" if prefix.endswith(',') else ","
        lines=[indent+k+": "+ts_render(v,indent)+"," for k,v in missing]
        close_indent=ts_indent_at(obj,close)
        obj=prefix+add_comma+"\n"+"\n".join(lines)+"\n"+close_indent+obj[close:]
    return src[:start]+obj+src[end:]

def enumerate_ts_questions(src):
    out=[]
    ids=list(re.finditer(r'\bid\s*:\s*["\'](t\d+-\d+)["\']',src))
