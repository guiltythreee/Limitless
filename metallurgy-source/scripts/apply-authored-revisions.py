def cue_audit(records):
    out=Counter(); lengths=[]; stems=Counter()
    for q in records:
        opts=q.get("options") if isinstance(q.get("options"),list) else []
        texts=[str(o.get("text","")) for o in opts]
        if len(texts)==4:
            lens=[len(t) for t in texts]
            if len(set(lens))>1 and lens.count(max(lens))==1: out["unique-longest-option"]+=1
            if min(lens)>0 and max(lens)>2*min(lens): out["option-over-2x-shortest"]+=1
            answer=q.get("answer")
            amap={o.get("label"):str(o.get("text","")) for o in opts if isinstance(o,dict)}
            if answer in amap and len(amap[answer])==max(lens) and lens.count(max(lens))==1: out["correct-option-uniquely-longest"]+=1
            if answer in amap and min(lens)>0 and len(amap[answer])>2*min(lens): out["correct-option-over-2x-shortest"]+=1
        if re.search(r'\b(all of the above|none of the above|all statements are correct|all are correct)\b'," ".join(texts),re.I): out["all-none-logic-candidate"]+=1
        if re.search(r'\b(always|never|only|must|impossible|completely|entirely)\b'," ".join(texts),re.I): out["absolute-word-candidate"]+=1
        if cue_references_label(q): out["option-letter-reference"]+=1
        explanation=" ".join(str(q.get(k,"")) for k in ("keyExplanation","concise","detailed","why","concept"))
        if re.search(r'\bP[123]\b',explanation): out["P1-P2-P3-pattern-code-reference"]+=1
        if q.get("statements") or q.get("type") in ("B","C","D","G","match","sequence"): out["structured-item-review-candidate"]+=1
        stem=re.sub(r'\s+',' ',str(q.get("text",q.get("text",""))).strip().lower())
        if stem: stems[stem]+=1
    out["duplicate-stem-groups"]=sum(1 for k,v in stems.items() if v>1)
    return out

