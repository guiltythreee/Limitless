    for p,content in writes.items():
        if not isinstance(content,str): raise SafeStop(f"Internal error: non-text output for {p}")
    try:
        for p,content in writes.items():
            p.parent.mkdir(parents=True,exist_ok=True)
            p.write_text(content,encoding="utf-8",newline="")
    except Exception:
        print("A write failed. Backup is available at:",backup)
        raise

    # Validate question data and persistent hooks from the files just written.
    for course in ("MT201","MT202"):
        for r in [x for x in REVISIONS if x["course"]==course]:
            ch=r["locator"]["chapter"]; n=r["locator"]["n"]
            q=find_json_question(json_read(src/"public"/"data"/course.lower()/f"{ch}.json"),n,course,ch)
            if q.get("type")!=r["originalType"]: raise SafeStop(f"Post-write type check failed: {course}/{ch} Q{n}")
            for k,v in r["updates"].items():
                # Shuffling is allowed to change answer/options after authored content is applied.
                if args.balance_answers and k in ("answer","options") and (ch,n) in shuffle_overrides[course]: continue
                if q.get(k)!=v: raise SafeStop(f"Post-write value check failed: {course}/{ch} Q{n} field {k}")
    for r in [x for x in REVISIONS if x["course"]=="MT203"]:
        qid=revision_question_id(r)
        path=src/"app"/"data"/"qbank"/(qid.split('-')[0]+".ts")
        text=path.read_text(encoding="utf-8")
        start,end=ts_question_span(text,qid); obj=text[start:end]
        props=ts_top_properties(obj); vals={k:parse_ts_literal(obj,a)[0] for k,(a,b) in props.items() if k in r["updates"]}
        # type and ID checks are always mandatory; option order may be changed by optional balancing.
        if vals.get("type")!=r["originalType"]: raise SafeStop(f"Post-write MT203 type check failed: {qid}")
        for k,v in r["updates"].items():
            if qid in ts_shuffled_ids and k in ("answer","options","distractors"):
                continue
            if vals.get(k)!=v: raise SafeStop(f"Post-write MT203 value check failed: {qid} field {k}")

