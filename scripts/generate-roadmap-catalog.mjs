// Generates roadmap/catalog.generated.mjs: the read-only facts the Progression Map needs
// about content that other modules own (Probability lessons and pathways, Metallurgy
// course question counts, Competition topic keys per subject).
//
// Why generate it: the map must stay correct when you add lessons, questions or
// competition topics. Copying those numbers by hand would let them drift silently.
//
// Usage (same loader the Studies catalogue generator uses):
//   node --experimental-strip-types --experimental-loader ./shared/learning-player/ts-extension-loader.mjs \
//        scripts/generate-roadmap-catalog.mjs [--write]
// Without --write it only checks that the committed file is current.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import vm from "node:vm";
import { PROBABILITY_STUDIES_REGISTRATION } from "../probability-source/app/studies/registration.ts";
import { MT201_MANIFEST } from "../metallurgy-source/app/courses/manifests/mt201.ts";
import { MT202_MANIFEST } from "../metallurgy-source/app/courses/manifests/mt202.ts";
import { MT203_MANIFEST } from "../metallurgy-source/app/courses/manifests/mt203.ts";

// ---- Probability: one lesson catalogue, several overlapping pathways -------------
const lessons = PROBABILITY_STUDIES_REGISTRATION.content.filter((item) => item.kind === "lesson");
const pathways = {};
for (const pathway of PROBABILITY_STUDIES_REGISTRATION.pathways) {
  pathways[pathway.id] = [...pathway.contentIds];
}

// ---- Metallurgy: topic question counts per course ----------------------------------
const courses = {};
for (const manifest of [MT201_MANIFEST, MT202_MANIFEST, MT203_MANIFEST]) {
  const topics = manifest.topics.map((topic) => ({ id: topic.id, count: topic.count }));
  courses[manifest.id] = {
    code: manifest.code,
    title: manifest.title,
    storageKey: manifest.storageKey,
    topics,
    bank: topics.reduce((sum, topic) => sum + topic.count, 0),
  };
}

// ---- Competition: topic keys grouped by subject ------------------------------------
// competition.js is a browser IIFE, so we do not import it. We evaluate only its two
// pure data literals (SUBJECTS and WEEKS) in an empty sandbox. If either literal is
// moved or renamed, this throws loudly instead of producing a wrong map.
const competitionSource = await readFile(resolve("competition/competition.js"), "utf8");
const start = competitionSource.indexOf("var SUBJECTS");
const weeksAt = competitionSource.indexOf("var WEEKS");
const end = competitionSource.indexOf("\n  ];\n", weeksAt);
if (start === -1 || weeksAt === -1 || end === -1) {
  throw new Error("Could not find SUBJECTS / WEEKS literals in competition/competition.js");
}
const sandbox = {};
vm.runInNewContext(competitionSource.slice(start, end + 6) + "\nthis.out = { SUBJECTS: SUBJECTS, WEEKS: WEEKS };", sandbox);
const { SUBJECTS, WEEKS } = sandbox.out;
const subjects = {};
for (const subject of SUBJECTS) subjects[subject.id] = [];
subjects.coding = []; // WEEKS also carries a coding topic that SUBJECTS does not list
WEEKS.forEach((week, weekIndex) => {
  week.topics.forEach((topic, topicIndex) => {
    // Must match competition.js topicKey(): 'w' + (week + 1) + '-t' + index
    (subjects[topic[0]] ??= []).push("w" + (weekIndex + 1) + "-t" + topicIndex);
  });
});

const catalog = {
  probability: { lessonCount: lessons.length, pathways },
  courses,
  competition: {
    weekCount: WEEKS.length,
    subjects,
    subjectLabels: Object.fromEntries(SUBJECTS.map((subject) => [subject.id, subject.name])),
  },
};

const output =
  "/* Generated by scripts/generate-roadmap-catalog.mjs. Do not edit by hand. */\n" +
  "export const ROADMAP_CATALOG = " + JSON.stringify(catalog, null, 2) + ";\n";
const outputPath = resolve("roadmap/catalog.generated.mjs");

if (process.argv.includes("--write")) {
  await writeFile(outputPath, output, "utf8");
  process.stdout.write("Wrote roadmap/catalog.generated.mjs\n");
} else {
  let existing = "";
  try { existing = await readFile(outputPath, "utf8"); } catch {}
  if (existing !== output) {
    process.stderr.write("roadmap/catalog.generated.mjs is stale. Run the generator with --write and commit the result.\n");
    process.exitCode = 1;
  } else {
    process.stdout.write("Roadmap catalogue is current.\n");
  }
}
